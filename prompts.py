def get_system_prompt(bot_name: str, available_stickers: List[str], text_only_mode: bool = True) -> str:
    """
    Generate the blended system prompt (all 5 roles at once, model picks).

    Kept for backward compatibility (used as Brain's default/casual fallback
    prompt). New code should prefer get_system_prompt_for_situation(), which
    gives the model exactly one role instead of five to average over.

    Args:
        bot_name: Name of the bot to use in the prompt
        available_stickers: List of available sticker emotions
        text_only_mode: If True, only text responses (no GIPHY/REACT/STICKER)

    Returns:
        Formatted system prompt string
    """
    blended_roles = "\n\n".join([
        "# ТВОИ СТОРОНЫ (все равноценны)",
        ROLE_BLOCK_JOKE,
        ROLE_BLOCK_HELP,
        ROLE_BLOCK_CASUAL,
        ROLE_BLOCK_TEASE,
        ROLE_BLOCK_DEFEND,
    ])
    return _get_base_prompt(bot_name, available_stickers, blended_roles, text_only_mode)


def get_system_prompt_for_situation(
    bot_name: str,
    available_stickers: List[str],
    situation: str = "casual",
    text_only_mode: bool = True,
    grudge_level: int = 0,
) -> str:
    """
    Generate a system prompt with exactly ONE role active, chosen upstream by
    ConversationAnalyzer.classify(). This is what fixes "не понимал в каком
    стиле ответить" — the model no longer has to guess/average between 5
    equally-weighted roles per message.

    Args:
        bot_name: Name of the bot to use in the prompt
        available_stickers: List of available sticker emotions
        situation: One of "joke" | "help" | "casual" | "tease" | "defend".
            Unknown values fall back to "casual".
        text_only_mode: If True, only text responses (no GIPHY/REACT/STICKER)
        grudge_level: For situation="defend" only — >=1 means this user has
            attacked the bot recently before, escalates the comeback tone.

    Returns:
        Formatted system prompt string with a single role section.
    """
    if situation == "defend":
        role_block = ROLE_BLOCK_DEFEND_ESCALATED if grudge_level >= 1 else ROLE_BLOCK_DEFEND
    else:
        role_block = SITUATION_BLOCKS.get(situation, ROLE_BLOCK_CASUAL)

    role_section = f"# КАК СЕЙЧАС ОТВЕЧАТЬ\n\n{role_block}"
    return _get_base_prompt(bot_name, available_stickers, role_section, text_only_mode)


def get_context_prompt(
    context: str, message_text: str, rag_facts: str = "", media_hint: str = ""
) -> str:
    """
    Generate the user prompt with context and current message.

    Args:
        context: Formatted recent messages
        message_text: Current message to respond to
        rag_facts: Optional facts retrieved from LightRAG knowledge base
        media_hint: Optional per-turn instruction about whether GIPHY:/REACT:/
            STICKER: is allowed this turn (see brain._build_media_hint).
            Placed last — instructions near the end of the prompt are
            followed more reliably than ones buried earlier.

    Returns:
        Formatted user prompt
    """
    # Facts go AFTER the recent messages for the same reason media_hint goes
    # last: the model follows what it read most recently. They used to sit at
    # the very top, ahead of ~40k characters of chat, which is the easiest
    # place in the prompt to lose.
    knowledge_block = ""
    if rag_facts:
        knowledge_block = f"""
---
ТВОЯ ПАМЯТЬ О ЧАТЕ (годы переписки этих же людей — ты всё это видел сам):
{rag_facts}
---
Отвечай по этой памяти: называй людей по именам, вспоминай конкретные случаи.
Если ответа в ней нет — так и скажи, но не отнекивайся, когда он есть.
"""

    media_block = f"\n\n[ФОРМАТ: {media_hint}]" if media_hint else ""

    return f"""Последние сообщения в чате:
{context}
{knowledge_block}
Новое сообщение для ответа: {message_text}{media_block}"""


# Bot name variations for mention detection.
# Historically a hardcoded list; now derived from BOT_NAME so detection follows
# whatever name the operator configures, with no extra code changes.
def get_name_variations(bot_name: str) -> List[str]:
    """
    Build mention-detection variants from the configured bot name.

    Covers common ways people type a name in chat: full form, glued (no space),
    dash-separated, and the first word as a short address ("Дип Сик" -> "дип").
    The short form is risky on its own (matches inside other words like
    "диплом"), so it's only added when the bot name is multi-word — single-word
    names rely on the full form.

    Args:
        bot_name: The configured BOT_NAME (e.g. "Дип Сик", "Вася")

    Returns:
        List of lowercase variants to match against incoming messages
    """
    name = (bot_name or "").strip().lower()
    if not name:
        return []

    variants = {name, name.replace(" ", ""), name.replace(" ", "-")}
    # For multi-word names, also accept the first word as a short address.
    parts = name.split()
    if len(parts) > 1 and len(parts[0]) >= 3:
        variants.add(parts[0])
    return [v for v in variants if len(v) >= 3]


